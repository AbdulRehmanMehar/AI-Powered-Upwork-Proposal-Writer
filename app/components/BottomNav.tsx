export default function BottomNav() {
  const pathname = usePathname();
  
  // Don't show on login/register pages
  if (pathname === '/login' || pathname === '/register') {
    return null;
  }

  return (
    <nav className="bottom-nav lg:hidden bg-zinc-900/95 backdrop-blur-lg border-t border-zinc-800">
      <div className="flex items-center justify-around h-16 px-2 max-w-lg mx-auto">
        {navItems.map((item) => {
          const isActive = pathname === item.href;
          
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex flex-col items-center justify-center flex-1 h-full px-2 py-1 rounded-xl transition-all ${
                isActive 
                  ? 'text-emerald-400' 
                  : 'text-zinc-500 hover:text-zinc-300 active:text-zinc-200'
              }`}
            >
              <div className={`transition-transform ${isActive ? 'scale-110' : ''}`}>
                {isActive && item.activeIcon ? item.activeIcon : item.icon}
              </div>
              <span className={`text-[10px] mt-1 font-medium ${isActive ? 'text-emerald-400' : ''}`}>
                {item.label}
              </span>
              {isActive && (
                <div className="absolute bottom-1 w-1 h-1 bg-emerald-400 rounded-full" />
              )}
            </Link>
          );
        })}
      </div>
    </nav>
  );
}
